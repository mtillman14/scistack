"""``docs/claude/ordered-groups-cases.json`` is what ``PlotSpec.ordered_groups`` says.

The GUI mirrors ``ordered_groups`` in ``PlotStudio/groups.ts``
(``orderGroups``), because the panel writes ``spec.groups`` on every role
change and must show the order the figure will draw. The TypeScript test
(``groups.cases.test.ts``) runs the cases in this file; this test makes
Python the owner of their expected answers:

* the case INPUTS are declared here (:data:`CASES`);
* the file holds each input plus Python's answer;
* a missing file is written; an existing one must match exactly, so a change
  to Python's rule fails here until the file is regenerated (delete it and
  rerun this test), and then fails the TypeScript side until it agrees.
"""

import json
from pathlib import Path

from scistackplot.model.spec import PlotSpec, Role

CASES_FILE = (
    Path(__file__).resolve().parents[2] / "docs" / "claude" / "ordered-groups-cases.json"
)

_DEPTHS = {"subject": 1, "InterventionGroup": 1, "session": 2, "trial": 3}

#: (name, roles, declared groups, depths or None). Roles map factor -> role
#: value; their ORDER is the holders' declaration order.
CASES: "list[tuple[str, dict[str, str], list[str], dict | None]]" = [
    ("the-list-is-the-users-order",
     {"subject": "group", "session": "group", "trial": "group"},
     ["session", "subject", "trial"], _DEPTHS),
    ("names-that-no-longer-group-are-dropped",
     {"subject": "group", "session": "collapse"}, ["session", "subject"], None),
    ("unordered-holders-deeper-first",
     {"subject": "group", "trial": "group"}, [], _DEPTHS),
    ("an-explicit-order-beats-depth",
     {"subject": "group", "trial": "group"}, ["subject", "trial"], _DEPTHS),
    ("no-depth-goes-innermost",
     {"subject": "group", "bandpass.low_hz": "group"}, [],
     {**_DEPTHS, "bandpass.low_hz": None}),
    ("equal-depths-keep-declaration-order",
     {"subject": "group", "InterventionGroup": "group"}, [], _DEPTHS),
    ("declared-first-then-rest-by-depth",
     {"session": "group", "subject": "group", "trial": "group", "bandpass.low_hz": "group"},
     ["subject"], {**_DEPTHS, "bandpass.low_hz": None}),
    ("two-depthless-keep-their-order",
     {"a.x": "group", "b.y": "group", "subject": "group"}, [], {"subject": 1}),
    ("a-declared-name-with-no-role-is-dropped",
     {"trial": "group"}, ["ghost", "trial"], _DEPTHS),
    ("no-depths-keeps-holder-order",
     {"trial": "group", "subject": "group", "session": "facet"}, [], None),
]


def _expected(roles: dict, declared: list, depths: "dict | None") -> list[str]:
    spec = PlotSpec(
        measures=["Measure"],
        roles={name: Role(value) for name, value in roles.items()},
        groups=list(declared),
    )
    return spec.ordered_groups(depths=depths)


def _document() -> dict:
    return {
        "about": [
            "GENERATED by scistackplot/tests/test_ordered_groups_cases.py from",
            "PlotSpec.ordered_groups. Do not edit by hand: delete the file and",
            "rerun that test. Read by PlotStudio/groups.cases.test.ts.",
            "roles: factor -> role, in declaration order. depths: null = none.",
        ],
        "cases": [
            {
                "name": name,
                "roles": roles,
                "declared": declared,
                "depths": depths,
                "expected": _expected(roles, declared, depths),
            }
            for name, roles, declared, depths in CASES
        ],
    }


def test_cases_file_is_current():
    document = _document()
    if not CASES_FILE.exists():
        CASES_FILE.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    on_disk = json.loads(CASES_FILE.read_text(encoding="utf-8"))
    assert on_disk == document, (
        f"{CASES_FILE.name} is stale: delete it and rerun this test, then run "
        "the frontend's npm test (groups.cases.test.ts)."
    )
