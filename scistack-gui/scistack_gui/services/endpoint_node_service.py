"""
Generated endpoints on the canvas: Plot/Stat Studio's "Add to pipeline" and
"Save … and add to pipeline" (GitHub issue #19).

A saved plot is a bookmark in the Studio. For reproducibility, saving can also
put the figure (and its statistics, when the plot carries test settings) on
the DAG as permanent ``plot_`` / ``stat_`` nodes:

1. **The function** is written into ``scistack_plots.py`` /
   ``scistack_stats.py`` beside the entities file, between generated markers::

       # scistack:generated plot id=<plot_id> -- regenerated on every save; ...
       def plot_step_length(df, filename): ...
       # scistack:end plot id=<plot_id>

   **The marker is the link** between a saved plot and its function — the one
   owner. Re-saving finds the block by id and replaces it (one function per
   saved plot, keeping the function name it was first given, so the node on
   the canvas keeps running the same function). A function of that name
   outside a block is never overwritten.
2. **The output variable** is declared through the normal entity path.
3. **The node** is placed in the current canvas scope with an edge from each
   input variable and to the output variable, and its settings stated: the
   output path (``pathOutputs``), the iteration level (``schemaLevel`` = the
   fan-out keys; ``[]`` = one call) and ``as_table``. All of that is
   rendered from ``EndpointCode.inputs`` — the same map the ``for_each``
   snippet is rendered from — so the canvas and the snippet cannot disagree.

What the canvas cannot express (a ``Variant(...)`` pin) is refused with the
reason (``scistackplotdb.why_not_wireable``); the function is still written.

Everything is logged under ``[endpoint-node]``.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass
from pathlib import Path

from scistack_gui.ids import ROOT_SCOPE
from scistack_gui.stores import history

logger = logging.getLogger(__name__)

#: kind -> (file name, header written into a new file)
FILES = {
    "plot": ("scistack_plots.py", '"""Plot endpoints generated by scistackplot."""\n'),
    "stat": ("scistack_stats.py", '"""Statistics endpoints generated by scistackstats."""\n'),
}


class EndpointWriteRefused(ValueError):
    """The function could not be written; the message says why and what to do."""


# ---------------------------------------------------------------------------
# Names
# ---------------------------------------------------------------------------


def _words(name: str) -> list[str]:
    return [w for w in re.split(r"[^0-9A-Za-z]+", name) if w]


def function_name_for(kind: str, saved_name: str) -> str:
    """``"Step length by group"`` -> ``plot_step_length_by_group``."""
    slug = "_".join(w.lower() for w in _words(saved_name)) or "figure"
    return f"{kind}_{slug}"


def output_variable_for(kind: str, saved_name: str) -> str:
    """``"Step length by group"`` -> ``StepLengthByGroupFigure`` / ``…Stats``."""
    camel = "".join(w[:1].upper() + w[1:] for w in _words(saved_name)) or "Saved"
    if camel[0].isdigit():
        camel = f"Plot{camel}"
    return camel + ("Figure" if kind == "plot" else "Stats")


# ---------------------------------------------------------------------------
# The generated block
# ---------------------------------------------------------------------------


def _start_marker(kind: str, owner_id: str) -> str:
    return f"# scistack:generated {kind} id={owner_id}"


def _end_marker(kind: str, owner_id: str) -> str:
    return f"# scistack:end {kind} id={owner_id}"


def endpoint_file(kind: str) -> Path:
    """Where *kind*'s generated functions live: beside the entities file (the
    project root, inside the discovery scope)."""
    from scistack_gui.services.target_file_service import get_or_create_target_file

    target_file, err = get_or_create_target_file()
    if target_file is None:
        raise EndpointWriteRefused(err or "No entities file to write beside.")
    return Path(target_file).parent / FILES[kind][0]


def _block_span(text: str, kind: str, owner_id: str) -> "tuple[int, int] | None":
    """``(start, end)`` character offsets of *owner_id*'s block, end marker line
    included, or ``None`` when there is none. A start marker without its end is
    a hand edit and is refused rather than guessed at."""
    start_line = _start_marker(kind, owner_id)
    start = text.find(start_line)
    if start < 0:
        return None
    end_line = _end_marker(kind, owner_id)
    end = text.find(end_line, start)
    if end < 0:
        raise EndpointWriteRefused(
            f"The generated block for this saved {kind} has lost its end marker "
            f"({end_line!r}); it was edited by hand. Restore the marker, or "
            f"save without adding to the pipeline."
        )
    return start, end + len(end_line)


_DEF_RE = re.compile(r"^def (\w+)\(", re.MULTILINE)


def generated_function_name(kind: str, owner_id: str) -> "str | None":
    """The function name *owner_id*'s block already defines, or ``None``.

    Re-saving keeps this name, so a renamed saved plot does not orphan the
    node that runs it."""
    path = endpoint_file(kind)
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    span = _block_span(text, kind, owner_id)
    if span is None:
        return None
    match = _DEF_RE.search(text[span[0] : span[1]])
    return match.group(1) if match else None


def write_function(
    kind: str, function_name: str, function_source: str, *, owner_id: "str | None" = None
) -> dict:
    """Write *function_source* into *kind*'s file and reload it.

    Without *owner_id* (plain "Add to pipeline"): appended, refused when the
    file already defines *function_name*. With it: written as *owner_id*'s
    generated block — replaced in place when the block exists, refused when
    *function_name* is defined anywhere else in the file.

    Returns ``{"file", "action": "appended"|"wrote"|"replaced"}``; raises
    :class:`EndpointWriteRefused`.
    """
    from scistack_gui.services.target_file_service import _reload_after_write

    path = endpoint_file(kind)
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    source = function_source.rstrip("\n") + "\n"
    span = _block_span(existing, kind, owner_id) if owner_id else None
    outside = existing if span is None else existing[: span[0]] + existing[span[1] :]
    if re.search(rf"^def {re.escape(function_name)}\(", outside, re.MULTILINE):
        raise EndpointWriteRefused(
            f"{path.name} already defines {function_name}"
            + (" outside this saved plot's generated block" if owner_id else "")
            + ". Choose a different name, or edit the existing one."
        )

    if owner_id:
        block = (
            f"{_start_marker(kind, owner_id)} -- regenerated on every save; "
            f"edit a copy outside these markers\n{source}{_end_marker(kind, owner_id)}"
        )
        if span is not None:
            text = existing[: span[0]] + block + existing[span[1] :]
            action = "replaced"
        else:
            text = (existing or FILES[kind][1]) + ("\n\n" if existing else "\n") + block + "\n"
            action = "wrote"
    else:
        text = (existing or FILES[kind][1]) + ("\n\n" if existing else "\n") + source
        action = "appended"

    history.note_write(path)
    path.write_text(text, encoding="utf-8")
    logger.info("[endpoint-node] %s %s in %s (owner=%s)", action, function_name, path, owner_id)
    reload_error = _reload_after_write(path)
    if reload_error:
        raise EndpointWriteRefused(f"{path.name} was written but did not load: {reload_error}")
    return {"file": str(path), "action": action}


def declare_output(output_variable: str) -> None:
    """Declare the endpoint's output type (an existing one is fine)."""
    from scistack_gui.services.target_file_service import validate_entity_name
    from scistack_gui.services.variable_service import create_variable

    name_error = validate_entity_name(output_variable)
    if name_error:
        raise EndpointWriteRefused(name_error)
    declared = create_variable(output_variable)
    if not declared.get("ok") and "already exists" not in str(declared.get("error", "")):
        raise EndpointWriteRefused(str(declared.get("error")))


# ---------------------------------------------------------------------------
# Placing the node
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class Wire:
    """One input of a generated endpoint, as the canvas states it: a variable
    edge (optionally one column) or an output path."""

    param: str
    variable: "str | None" = None
    column: "str | None" = None
    template: "str | None" = None


def plot_wires(code) -> "tuple[list[Wire], str | None]":
    """``(wires, why not)`` from a ``scistackplotdb.EndpointCode``."""
    from scistackplotdb import why_not_wireable

    reason = why_not_wireable(code.inputs)
    wires = [
        Wire(param, variable=i.variable, column=i.column, template=i.template)
        for param, i in code.inputs.items()
    ]
    return wires, reason


def stat_wires(code) -> "list[Wire]":
    """From a ``scistackstatsdb.StatsEndpointCode``: its inputs are plain
    variables by construction (``scistackstats.why_not_exportable``)."""
    return [Wire(param, variable=variable) for param, variable in code.inputs.items()]


def _canvas(db, scope: str) -> "tuple[dict[tuple[str, str], str], list[dict]]":
    """``({(node type, label): node id}, edges)`` of what *scope*'s canvas shows
    — history-derived edges included, which the stored edge rows are not."""
    from scistack_gui.services.pipeline_service import get_pipeline_graph

    graph = get_pipeline_graph(db, scope, run_states=False)
    found: dict[tuple[str, str], str] = {}
    for node in graph.get("nodes", []):
        label = (node.get("data") or {}).get("label")
        if label:
            found.setdefault((node.get("type"), label), node["id"])
    return found, list(graph.get("edges", []))


def _next_column_x(scope: str) -> "tuple[float, float]":
    """A free spot: right of everything on the canvas."""
    from scistack_gui.stores import layout as layout_store

    positions = layout_store.read_layout(scope).get("positions") or {}
    xs = [p.get("x", 0) for p in positions.values() if isinstance(p, dict)]
    ys = [p.get("y", 0) for p in positions.values() if isinstance(p, dict)]
    return (max(xs) + 320 if xs else 0.0), (min(ys) if ys else 0.0)


def place(
    db,
    *,
    function_name: str,
    output_variable: str,
    wires: "list[Wire]",
    as_table: "list[str]",
    iterate_keys: "list[str]",
    scope: str = ROOT_SCOPE,
) -> dict:
    """Put *function_name* on *scope*'s canvas, wired and configured.

    Idempotent: a function node already showing *function_name* is reused,
    and an input already wired on it is left alone. The settings derived from
    the spec (output paths, iteration level, ``as_table``, column picks) are
    re-stated on every call — saving owns them — while the node's own
    location filters and other run options are kept.

    Returns ``{"node_id", "placed": bool, "edges": n}``.
    """
    from scistack_gui import ids
    from scistack_gui.services import layout_service
    from scistack_gui.stores import pipeline_store

    nodes, drawn = _canvas(db, scope)
    x0, y0 = _next_column_x(scope)
    fn_id = nodes.get(("functionNode", function_name))
    placed = fn_id is None
    if placed:
        fn_id = ids.new_manual_node_id("functionNode", function_name)
        layout_service.put_layout(fn_id, x0 + 260, y0, "functionNode", function_name, scope)

    def variable_node(label: str, x: float, y: float) -> str:
        node_id = nodes.get(("variableNode", label))
        if node_id is None:
            node_id = ids.new_manual_node_id("variableNode", label)
            layout_service.put_layout(node_id, x, y, "variableNode", label, scope)
            nodes[("variableNode", label)] = node_id
        return node_id

    wired_handles = {
        e.get("targetHandle") for e in drawn if ids.strip_placement(e.get("target", "")) == ids.strip_placement(fn_id)
    }
    has_output_edge = any(
        ids.strip_placement(e.get("source", "")) == ids.strip_placement(fn_id) for e in drawn
    )

    n_edges = 0
    for row, wire in enumerate(w for w in wires if w.variable):
        handle = ids.in_handle(wire.param)
        if handle in wired_handles:
            logger.info("[endpoint-node] %s: %r already wired, kept", function_name, wire.param)
            continue
        source = variable_node(wire.variable, x0, y0 + 110 * row)
        layout_service.put_edge(db, ids.new_manual_edge_id(), source, fn_id, None, handle)
        n_edges += 1
    if not has_output_edge:
        target = variable_node(output_variable, x0 + 560, y0)
        layout_service.put_edge(
            db, ids.new_manual_edge_id(), fn_id, target, ids.out_handle(output_variable), None
        )
        n_edges += 1

    stored = pipeline_store.get_node_config(db, fn_id) or {}
    config = {
        "pathOutputs": {w.param: w.template for w in wires if w.template},
        "schemaLevel": list(iterate_keys),
        "schemaSelection": stored.get("schemaSelection"),
        "whereFilters": stored.get("whereFilters"),
        "runOptions": {**(stored.get("runOptions") or {}), "as_table": list(as_table)},
        "columnSelections": {
            **(stored.get("columnSelections") or {}),
            **{
                w.param: {"columns": [w.column], "iterate": False}
                for w in wires
                if w.variable and w.column
            },
        },
    }
    config = {k: v for k, v in config.items() if v is not None}
    layout_service.put_node_config(db, fn_id, config)
    layout_service._notify_dag_updated("endpoint_node_service.place")
    logger.info(
        "[endpoint-node] %s %s on scope %r as %s: %d edge(s) drawn, level=%s, as_table=%s, "
        "output paths=%s",
        "placed" if placed else "updated",
        function_name,
        scope,
        fn_id,
        n_edges,
        iterate_keys or "one call",
        as_table,
        config.get("pathOutputs"),
    )
    return {"node_id": fn_id, "placed": placed, "edges": n_edges}


# ---------------------------------------------------------------------------
# Saving a plot onto the canvas
# ---------------------------------------------------------------------------


def _plot_onto_canvas(db, plot_id: str, saved_name: str, spec_payload: dict, scope: str) -> dict:
    from scistack_gui.services import plot_service

    name = generated_function_name("plot", plot_id) or function_name_for("plot", saved_name)
    code = plot_service.generate_code(
        db, spec_payload, function_name=name, output_variable=output_variable_for("plot", saved_name)
    )
    declare_output(code.output_variable)
    written = write_function("plot", code.function_name, code.function_source, owner_id=plot_id)
    wires, reason = plot_wires(code)
    result = {"kind": "plot", "function_name": code.function_name, "output_variable": code.output_variable,
              "foreach_source": code.foreach_source, **written}
    if reason:
        logger.warning("[endpoint-node] %s not placed: %s", code.function_name, reason)
        return {**result, "placed": False, "skipped": reason}
    placed = place(db, function_name=code.function_name, output_variable=code.output_variable, wires=wires,
                   as_table=code.as_table, iterate_keys=code.iterate_keys, scope=scope)
    return {**result, **placed}


def _stats_onto_canvas(db, plot_id: str, saved_name: str, spec_payload: dict, stats: dict, scope: str) -> dict:
    from scistackstats import NotExportable
    from scistackstatsdb import generate_stats_endpoint

    from scistack_gui.services import stats_service

    spec = stats_service._spec({**stats, "design": spec_payload, "format": 1})
    tables = stats_service._tables(db, spec, csv_path=None, label="stats_onto_canvas")
    name = generated_function_name("stat", plot_id) or function_name_for("stat", saved_name)
    try:
        code = generate_stats_endpoint(spec, tables, function_name=name,
                                       output_variable=output_variable_for("stat", saved_name))
    except NotExportable as exc:
        reason = f"the statistics are not exportable yet: {exc}"
        logger.warning("[endpoint-node] stat_ for %s not placed: %s", saved_name, reason)
        return {"kind": "stat", "placed": False, "skipped": reason}
    declare_output(code.output_variable)
    written = write_function("stat", code.function_name, code.function_source, owner_id=plot_id)
    # A stat_ endpoint makes one record over the whole table: one call.
    placed = place(db, function_name=code.function_name, output_variable=code.output_variable,
                   wires=stat_wires(code), as_table=list(code.inputs), iterate_keys=[], scope=scope)
    return {"kind": "stat", "function_name": code.function_name, "output_variable": code.output_variable,
            "foreach_source": code.foreach_source, **written, **placed}


def save_onto_canvas(
    db,
    *,
    plot_id: str,
    saved_name: str,
    spec_payload: dict,
    stats: "dict | None" = None,
    scope: str = ROOT_SCOPE,
) -> list[dict]:
    """The saved plot (and its statistics, if any) as nodes on *scope*'s canvas.

    One entry per endpoint: ``{kind, function_name, file, action, node_id,
    placed, edges}`` or ``{kind, placed: False, skipped | error}``. Never
    raises: the saved plot is already saved, and a problem here is reported
    beside it rather than failing the save.
    """
    results: list[dict] = []
    steps = [("plot", lambda: _plot_onto_canvas(db, plot_id, saved_name, spec_payload, scope))]
    if stats:
        steps.append(("stat", lambda: _stats_onto_canvas(db, plot_id, saved_name, spec_payload, stats, scope)))
    for kind, step in steps:
        try:
            results.append(step())
        except (EndpointWriteRefused, ValueError) as exc:
            logger.warning("[endpoint-node] %s for saved plot %s (%s): %s", kind, saved_name, plot_id, exc)
            results.append({"kind": kind, "placed": False, "error": str(exc)})
        except Exception as exc:  # reported beside the save, with the traceback in the log
            logger.exception("[endpoint-node] %s for saved plot %s (%s) failed", kind, saved_name, plot_id)
            results.append({"kind": kind, "placed": False, "error": f"{type(exc).__name__}: {exc}"})
    return results
